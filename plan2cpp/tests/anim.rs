//! CSS animations: the values plan2cpp admits, its refusals, and the samples
//! Exact's motion crate gives for the anim test app, which `anim_check`
//! compares the C++ sampler with.
#![allow(clippy::panic, reason = "a test fails by panicking")]

use std::fmt::Write;
use std::path::{Path, PathBuf};

use exact_motion::{Property, Value};

fn repo() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("..")
}

fn plan(source: &str) -> exact_plan::Plan {
    contract::compile(source).unwrap_or_else(|e| panic!("{e}"))
}

const APP: &str = "rt-test/anim/app.contract";
const REFERENCE: &str = "rt-test/anim/reference.h";

/// Local times sampled, in ms: before and after delays, inside and at the
/// ends of iterations, and past the end.
const TIMES: [f64; 10] = [
    0.0, 100.0, 250.0, 500.0, 750.0, 999.0, 1000.0, 1250.0, 1500.0, 2500.0,
];

/// The properties the board animates, as `rt::AP` names, with the value each
/// sample is taken over.
fn properties() -> [(Property, &'static str, Value); 8] {
    let white = Value::rgba8(255, 255, 255, 255);
    [
        (Property::Translate, "Translate", Value::ZERO),
        (Property::Opacity, "Opacity", Value::scalar(1.0)),
        (Property::Color, "Color", white),
        (Property::BackgroundColor, "BackgroundColor", white),
        (Property::BorderTopColor, "BorderTopColor", white),
        (Property::BorderRightColor, "BorderRightColor", white),
        (Property::BorderBottomColor, "BorderBottomColor", white),
        (Property::BorderLeftColor, "BorderLeftColor", white),
    ]
}

/// The reference header: each table animation's samples at `TIMES`.
fn reference() -> String {
    let path = repo().join(APP);
    let plan = contract::compile_path(&path).unwrap_or_else(|e| panic!("{e}"));
    let values = plan2cpp::anim::values(&plan).unwrap_or_else(|e| panic!("{e}"));
    let mut rows = Vec::new();
    for (v, (_, animations)) in values.iter().enumerate() {
        for (k, a) in animations.0.iter().enumerate() {
            for (p, name, under) in properties() {
                if !a
                    .keyframes
                    .0
                    .iter()
                    .any(|f| f.values.iter().any(|(q, _)| *q == p))
                {
                    continue;
                }
                for t in TIMES {
                    let sample = a.sample(t / 1000.0, p, under);
                    let c = sample.unwrap_or(Value::ZERO).components();
                    rows.push(format!(
                        "    {{{v}, {k}, rt::AP::{name}, {t:?}, {}, {{{:?}, {:?}, {:?}, {:?}}}}},",
                        sample.is_some(),
                        c[0],
                        c[1],
                        c[2],
                        c[3]
                    ));
                }
            }
        }
    }
    let mut out = String::new();
    let _ = writeln!(
        out,
        "// Generated by plan2cpp's tests (tests/anim.rs) from {APP} with Exact's motion crate.\n\
         // Do not edit; PLAN2CPP_BLESS=1 cargo test -p plan2cpp --test anim writes it.\n\
         // Each row: an animation value's index, the animation's index in it, a property,\n\
         // local time in ms, whether it has an effect then, and its value over white (a\n\
         // color), 1 (opacity), or none (translate).\n\
         #pragma once\n\n#include \"exact_rt.h\"\n\nnamespace reference {{\n\n\
         struct Sample {{\n  uint16_t value, animation;\n  rt::AP prop;\n  double t_ms;\n  bool has;\n  double v[4];\n}};\n\n\
         const Sample kSamples[] = {{"
    );
    out.push_str(&rows.join("\n"));
    out.push_str("\n};\n\n}  // namespace reference\n");
    out
}

#[test]
fn the_committed_reference_samples_are_exacts() {
    let made = reference();
    let file = repo().join(REFERENCE);
    if std::env::var_os("PLAN2CPP_BLESS").is_some() {
        std::fs::write(&file, &made).unwrap_or_else(|e| panic!("{e}"));
    }
    let committed = std::fs::read_to_string(&file).unwrap_or_else(|e| panic!("{e}"));
    assert_eq!(
        committed, made,
        "{REFERENCE} is stale; run PLAN2CPP_BLESS=1 cargo test -p plan2cpp --test anim"
    );
}

#[test]
fn the_anim_apps_committed_tables_are_current() {
    let source = repo().join(APP);
    let plan = contract::compile_path(&source).unwrap_or_else(|e| panic!("{e}"));
    let cpp = plan2cpp::emit(&plan, &source).unwrap_or_else(|e| panic!("{e}"));
    let committed = std::fs::read_to_string(repo().join("rt-test/anim/app_gen.cpp"))
        .unwrap_or_else(|e| panic!("{e}"));
    let made = cpp.replace(&source.display().to_string(), APP);
    assert_eq!(
        committed, made,
        "rt-test/anim/app_gen.cpp is stale; run plan2cpp emit"
    );
}

#[test]
fn only_literals_whose_names_all_resolve_are_animation_values() {
    let p = plan(
        "keyframes fade\n  from opacity=0\n  to opacity=1\ncomponent A\n  view\n    column\n      text \"a\" animation=\"fade 1s\"\n      text \"fade 2s, other 1s\"\n      text \"hello\"\n",
    );
    let values = plan2cpp::anim::values(&p).unwrap_or_else(|e| panic!("{e}"));
    let texts: Vec<&str> = values.iter().map(|(t, _)| t.as_str()).collect();
    assert!(texts.contains(&"fade 1s"), "{texts:?}");
    assert!(!texts.contains(&"fade 2s, other 1s"), "{texts:?}");
    assert!(!texts.contains(&"hello"), "{texts:?}");
}

#[test]
fn a_property_the_board_does_not_animate_is_refused_by_name() {
    let source = "keyframes grow\n  from scale=1\n  to scale=2\ncomponent A\n  view\n    text \"a\" animation=\"grow 1s\"\n";
    let err = plan2cpp::emit(&plan(source), Path::new("a.contract"))
        .err()
        .unwrap_or_default();
    assert!(err.contains("it animates `scale`"), "{err}");
}
